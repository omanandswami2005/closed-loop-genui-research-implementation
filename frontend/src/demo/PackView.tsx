import { ArrowRight, Loader2 } from "lucide-react";
import { useEffect, useState } from "react";
import { Btn, Panel } from "../clt/Panel";
import { demoApi } from "./api";
import type { LearnerReport, PackSummary } from "./types";
import { go } from "./useRoute";

const KIND = { pdf: "PDF pages", pptx: "slides", markdown: "lines", text: "lines", paste: "lines" } as Record<string, string>;

export function PackView({ id, learnerId, cached }: { id: string; learnerId: string; cached: boolean }) {
  const [pack, setPack] = useState<PackSummary | null>(null);
  const [report, setReport] = useState<LearnerReport | null>(null);
  const [starting, setStarting] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    demoApi.pack(id).then(setPack, (e) => setError(e.message));
    demoApi.report(learnerId).then(setReport, () => setReport(null));
  }, [id, learnerId]);

  const start = async (topicId: string) => {
    setStarting(topicId);
    setError(null);
    try {
      const view = await demoApi.startSession(learnerId, id, topicId);
      go(`/learn/${view.session_id}`);
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
      setStarting(null);
    }
  };

  if (error && !pack) return <p className="p-4 font-mono text-xs text-red-300">{error}</p>;
  if (!pack) return <p className="p-4 font-mono text-xs text-slate-400">loading…</p>;
  const status = (tid: string) => report?.topics.find((t) => t.pack_id === id && t.topic_id === tid);

  return (
    <main className="mx-auto flex max-w-6xl flex-col gap-4 p-4">
      <div className="flex flex-wrap items-end justify-between gap-3 border border-zinc-800 bg-white px-4 py-3 text-slate-900">
        <div>
          <span className="font-mono text-[11px] uppercase tracking-[0.14em] text-slate-500">material</span>
          <h2 data-testid="pack-title" className="text-lg font-semibold">
            {pack.title}
          </h2>
        </div>
        <dl className="grid grid-cols-2 gap-x-4 gap-y-0.5 font-mono text-[11px] text-slate-600 sm:grid-cols-4">
          <dt className="text-slate-400">source</dt>
          <dd className="truncate">{pack.source_name}</dd>
          <dt className="text-slate-400">extracted</dt>
          <dd>
            {pack.chars.toLocaleString()} chars · {pack.source_units} {KIND[pack.source_kind] ?? ""}
            {pack.truncated ? " (truncated)" : ""}
          </dd>
          <dt className="text-slate-400">generated by</dt>
          <dd>
            {pack.model} · {(pack.generation_ms / 1000).toFixed(1)} s{cached ? " · this upload served from cache" : ""}
          </dd>
          <dt className="text-slate-400">validation</dt>
          <dd>{pack.dropped_questions} questions dropped</dd>
        </dl>
      </div>
      {error && <p className="border border-red-700 px-3 py-2 font-mono text-xs text-red-300">{error}</p>}
      <div className="grid gap-4 md:grid-cols-2" data-testid="topics">
        {pack.topics.map((t, i) => {
          const s = status(t.id);
          return (
            <Panel
              key={t.id}
              code={`T${i + 1}`}
              title={t.title}
              meta={s ? `${s.status} · P(L) ${s.mastery_now.toFixed(2)}` : `${t.questions} questions`}
            >
              <p className="text-sm text-slate-700">{t.summary}</p>
              <ul className="mt-2 space-y-1 border-l-2 border-zinc-200 pl-3 text-[13px] text-slate-600">
                {t.key_points.map((k) => (
                  <li key={k}>{k}</li>
                ))}
              </ul>
              <div className="mt-3 flex items-center justify-between">
                <span className="font-mono text-[11px] text-slate-500">4 levels: recognise · understand · recall · apply</span>
                <Btn variant="primary" disabled={starting !== null} onClick={() => void start(t.id)}>
                  <span data-testid={`learn-${t.id}`} className="flex items-center gap-1.5">
                    {starting === t.id ? <Loader2 size={12} className="animate-spin" aria-hidden /> : <ArrowRight size={12} aria-hidden />}
                    {s ? "learn again" : "learn this topic"}
                  </span>
                </Btn>
              </div>
            </Panel>
          );
        })}
      </div>
    </main>
  );
}
